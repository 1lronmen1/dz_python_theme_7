"""**Задание 2 (не обязательное)**

*Напишите функцию date_range, которая возвращает список дат за период от start_date до end_date. Даты должны вводиться в формате YYYY-MM-DD. В случае неверного формата или при start_date > end_date должен возвращаться пустой список.*

*Примеры работы программы:*

```
date_range(‘2022-01-01’, ‘2022-01-03’)

[‘2022-01-01’, ‘2022-01-02’, ‘2022-01-03’]
```


"""

from datetime import datetime, timedelta

def date_range(start_date, end_date, date_format="%Y-%m-%d"):
    """
    Возвращает список дат от start_date до end_date включительно.
    Формат даты по умолчанию: YYYY-MM-DD.
    """
    # Генерация пустого списка дат
    dates_list = []

    # Проверка формата даты
    try:
        start_date_datetime = datetime.strptime(start_date, date_format)
        end_date_datetime = datetime.strptime(end_date, date_format)
    except ValueError:
        # Если формат не совпадает, возвращаем пустой список
        return dates_list

    # Проверка: дата начала не должна быть больше даты конца
    if start_date_datetime > end_date_datetime:
        return dates_list

    while start_date_datetime <= end_date_datetime:
        # Форматируем дату обратно в строку и добавляем в список
        dates_list.append(start_date_datetime.strftime(date_format))
        # Прибавляем 1 день
        start_date_datetime += timedelta(days=1)

    return dates_list

# Проверки в рамках ДЗ
print(date_range('2022-01-01', '2022-01-03'))
print(date_range('2022-01-03', '2022-01-01'))
print(date_range('2022-02-30', '2022-02-31'))